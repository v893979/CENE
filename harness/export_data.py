"""Export every scenario's synthetic data products to CSV so they can be inspected.

    python -m harness.export_data            # writes data/<product>.csv and data/<product>__ref_<mode>.csv
                                             # plus data/DATA_DICTIONARY.md

The CSVs are exactly what the scenarios start from (same generators, same seeds), before any
fault is injected.
"""
from __future__ import annotations

from pathlib import Path

from .datagen import generate
from .runner import load_scenarios

OUT = Path(__file__).resolve().parent.parent / "data"


def _describe(spec: dict) -> str:
    g = spec["gen"]
    if g == "seq":
        return f"sequence {spec.get('prefix', '')}{'0' * int(spec.get('digits', 6))}+"
    if g == "choice":
        vals = spec["values"]
        return "one of " + (", ".join(map(str, vals)) if len(vals) <= 6 else f"{len(vals)} values")
    if g == "map":
        return f"derived from {spec['from']} (fixed mapping)"
    if g in ("normal", "int"):
        return f"normal(mean {spec['mean']}, sd {spec['sd']})" + (f", clipped {spec['clip']}" if "clip" in spec else "")
    if g == "lognormal":
        return f"lognormal(mu {spec['mean']}, sigma {spec['sigma']})" + (f", clipped {spec['clip']}" if "clip" in spec else "")
    if g == "const":
        return f"constant '{spec['value']}'"
    if g == "maybe":
        return f"{_describe(spec['of'])}, null with probability {spec['p_null']}"
    return g


def main():
    OUT.mkdir(exist_ok=True)
    lines = ["# Data dictionary (generated by `python -m harness.export_data`)", "",
             "All data is synthetic. Values come from the generators below with fixed seeds.", ""]
    for sc in load_scenarios():
        for prod, spec in sc["data"].items():
            seed = int(spec.get("seed", 1))
            df = generate(spec["columns"], int(spec["rows"]), seed)
            df.to_csv(OUT / f"{prod}.csv", index=False)
            ref = generate(spec["columns"], int(spec.get("reference_rows", 1000)), seed + 1000, start=500000)
            ref.to_csv(OUT / f"{prod}__ref_baseline.csv", index=False)
            files = [f"{prod}.csv", f"{prod}__ref_baseline.csv"]
            for name, prof in (spec.get("profiles") or {}).items():
                generate(spec["columns"], int(spec.get("reference_rows", 1000)), seed + 2000, start=600000,
                         overrides=prof.get("overrides")).to_csv(OUT / f"{prod}__ref_{name}.csv", index=False)
                files.append(f"{prod}__ref_{name}.csv")
            contract = next(c for c in sc["contracts"] if c["product"] == prod)
            lines += [f"## {prod} ({sc['id']}: {sc['title']})", "",
                      f"{spec['rows']} rows, seed {seed}; reference profile 1,000 rows. Files: "
                      + ", ".join(f"`{f}`" for f in files), "",
                      "| Column | Type | Criticality | Contract rule | Generated as |", "|---|---|---|---|---|"]
            for col, cs in contract["columns"].items():
                rule = ", ".join(f"{k} {v}" for k, v in cs.items() if k in ("pattern", "allowed", "min", "max"))
                gen = _describe(spec["columns"][col])
                lines.append(f"| {col} | {cs['type']} | {cs.get('criticality', 1)} | {rule.replace('|', '/')} | {gen} |")
            for name, prof in (spec.get("profiles") or {}).items():
                for col, ov in prof.get("overrides", {}).items():
                    lines.append(f"| {col} ({name} profile) | | | | {_describe(ov)} |")
            lines.append("")
    (OUT / "DATA_DICTIONARY.md").write_text("\n".join(lines))
    print(f"wrote {len(list(OUT.glob('*.csv')))} CSV files and DATA_DICTIONARY.md to {OUT}")


if __name__ == "__main__":
    main()
